/****************************************************************************
 * Public Functions
 ****************************************************************************/

const char *signbridge_vocab_get(int class_id)
{
  if (class_id < 0 || class_id >= SIGNBRIDGE_VOCAB_SIZE)
    {
      return NULL;
    }

  return g_vocab_table[class_id];
}
